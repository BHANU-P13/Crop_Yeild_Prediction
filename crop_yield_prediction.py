import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# 1. LOAD DATASET
# ==========================================

df = pd.read_csv("crop_yield_prediction_dataset.csv")

print("\n========== ORIGINAL DATASET ==========")
print("Dataset Shape:", df.shape)
print(df.head())

# ==========================================
# 2. DATA CLEANING
# ==========================================

required_crops = ["rice", "wheat", "maize", "sugarcane"]

data = df[
    (df["measure"].astype(str).str.lower() == "yield") &
    (df["commodity"].astype(str).str.lower().isin(required_crops)) &
    (df["region_kind"].astype(str).str.lower().isin(["state", "ut"])) &
    (df["unit"].astype(str).str.lower() == "kg_ha")
].copy()

data = data.rename(columns={
    "region_name": "state",
    "value": "crop_yield"
})

data["crop"] = data["commodity"].astype(str).str.lower()
data["crop_name"] = data["crop"].str.title()

data["year"] = data["period"].astype(str).str.extract(r"(20\d{2})")
data["year"] = pd.to_numeric(data["year"], errors="coerce")
data["crop_yield"] = pd.to_numeric(data["crop_yield"], errors="coerce")

data = data.dropna(subset=["state", "crop", "year", "crop_yield"])
data = data[data["crop_yield"] > 0]

data = data.groupby(
    ["crop", "crop_name", "state", "year"],
    as_index=False
)["crop_yield"].mean()

data["year"] = data["year"].astype(int)

all_states = sorted(data["state"].unique())
all_crops = sorted(data["crop"].unique())

print("\n========== CLEANED DATASET ==========")
print("Cleaned Dataset Shape:", data.shape)
print("Available Crops:", all_crops)
print("Number of States/UTs:", len(all_states))
print("Available Years:", sorted(data["year"].unique()))

data.to_csv("cleaned_crop_yield.csv", index=False)

# ==========================================
# 3. EXPLORATORY DATA ANALYSIS
# ==========================================

print("\n========== CROP-WISE AVERAGE YIELD ==========")

crop_average = data.groupby("crop_name")["crop_yield"].mean()
