# ==========================================
# 4. OUTLIER DETECTION USING IQR
# ==========================================

print("\n========== OUTLIER DETECTION ==========")

for crop in all_crops:

    values = data[data["crop"] == crop]["crop_yield"]

    Q1 = values.quantile(0.25)
    Q3 = values.quantile(0.75)

    IQR = Q3 - Q1

    lower_limit = Q1 - 1.5 * IQR
    upper_limit = Q3 + 1.5 * IQR

    outliers = values[
        (values < lower_limit) |
        (values > upper_limit)
    ]

    print(crop.title(), "Outliers:", len(outliers))

# ==========================================
# 5. TRAIN-TEST SPLIT
# ==========================================

train_data = data[data["year"] < 2024].copy()
test_data = data[data["year"] == 2024].copy()

if train_data.empty or test_data.empty:
    raise ValueError("Dataset must contain training years before 2024 and test data for 2024.")

print("\n========== TRAIN TEST SPLIT ==========")
print("Training Rows:", len(train_data))
print("Testing Rows:", len(test_data))

# ==========================================
# 6. FEATURE ENCODING
# ==========================================

year_center = 2021
year_scale = 10.0

def make_features(frame):

    state_values = pd.Categorical(
        frame["state"],
        categories=all_states
    )

    crop_values = pd.Categorical(
        frame["crop"],
        categories=all_crops
    )

    state_encoded = pd.get_dummies(
        state_values,
        dtype=float
    ).to_numpy()

    crop_encoded = pd.get_dummies(
        crop_values,
        dtype=float
    ).to_numpy()

    year_values = frame["year"].to_numpy(dtype=float).reshape(-1, 1)

    # Continuous year variable
    year_scaled = (year_values - year_center) / year_scale

    features = np.hstack([
        np.ones((len(frame), 1)),
        state_encoded,
        crop_encoded,
        year_scaled
    ])

    return features

# ==========================================
# 7. LINEAR REGRESSION MODEL
# ==========================================

X_train = make_features(train_data)
X_test = make_features(test_data)

# Log transformation of crop yield
y_train = np.log(train_data["crop_yield"].to_numpy())
y_test_actual = test_data["crop_yield"].to_numpy()

# Calculate regression coefficients
coefficients = np.linalg.lstsq(
    X_train,
    y_train,
    rcond=None
)[0]

# Predict log yield
log_predictions = X_test @ coefficients

# Convert predictions back to kg/ha
test_predictions = np.exp(log_predictions)

# ==========================================
# 8. MODEL EVALUATION
# ==========================================

def evaluate_model(actual, predicted):

    MAE = np.mean(np.abs(actual - predicted))

    MSE = np.mean((actual - predicted) ** 2)

    RMSE = np.sqrt(MSE)

    SS_total = np.sum((actual - np.mean(actual)) ** 2)

    SS_residual = np.sum((actual - predicted) ** 2)

    R2 = (
        1 - SS_residual / SS_total
        if SS_total != 0 else np.nan
    )

    return MAE, MSE, RMSE, R2


metrics = evaluate_model(y_test_actual, test_predictions)

print("\n========== MODEL EVALUATION ==========")
print("Model: Log-Linear Regression")
print("MAE:", round(metrics[0], 2))
print("MSE:", round(metrics[1], 2))
print("RMSE:", round(metrics[2], 2))
print("R2 Score:", round(metrics[3], 4))

evaluation = pd.DataFrame({
    "Model": ["Log-Linear Regression"],
    "MAE": [metrics[0]],
    "MSE": [metrics[1]],
    "RMSE": [metrics[2]],
    "R2 Score": [metrics[3]]
})

evaluation.to_csv("model_evaluation.csv", index=False)

