print(df.head())

# ==========================================
# 2. DATA CLEANING AND PREPROCESSING
# ==========================================

print("\nMissing values:")
print(df.isnull().sum())

print("\nDuplicate records:", df.duplicated().sum())

required_crops = ["rice", "wheat", "maize", "sugarcane"]

data = df[
    (df["measure"].str.lower() == "yield") &
    (df["commodity"].str.lower().isin(required_crops)) &
    (df["region_kind"].str.lower().isin(["state", "ut"])) &
    (df["unit"].str.lower() == "kg_ha")
].copy()

data = data.rename(columns={
    "region_name": "state",
    "value": "crop_yield"
})

# Keep crop names for display and crop codes for model training
data["crop_name"] = data["commodity_name"]
data["crop"] = data["commodity"].str.lower()

# Extract year from agricultural period
data["year"] = data["period"].astype(str).str.extract(r"(\d{4})")
data["year"] = pd.to_numeric(data["year"], errors="coerce")

data["crop_yield"] = pd.to_numeric(
    data["crop_yield"], errors="coerce"
)

# Remove missing values
data = data.dropna(
    subset=["crop", "state", "year", "crop_yield"]
)

# Remove zero and negative values
data = data[data["crop_yield"] > 0]

data["year"] = data["year"].astype(int)

# Average repeated crop-state-year records
data = data.groupby(
    ["crop", "state", "year"],
    as_index=False
).agg({
    "crop_yield": "mean",
    "crop_name": "first"
})

print("\nCLEANED DATASET")
print("Final dataset shape:", data.shape)

print("\nCrop counts:")
print(data["crop_name"].value_counts())

print("\nNumber of states and UTs:", data["state"].nunique())
print("Available years:", sorted(data["year"].unique()))

data.to_csv("cleaned_crop_yield.csv", index=False)

