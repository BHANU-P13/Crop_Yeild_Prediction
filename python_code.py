def predict_crop_yield(state, crop, year):

    state = state.strip()
    crop = crop.strip().lower()

    # Validate crop
    if crop not in required_crops:

        print("\nInvalid crop!")
        print("Available crops:", required_crops)
        return

    # Match state without case sensitivity
    matching_states = {
        s.strip().lower(): s
        for s in data["state"].unique()
    }

    if state.lower() not in matching_states:

        print("\nInvalid state or UT!")
        print("Available states/UTs:")
        print(sorted(data["state"].unique()))
        return

    state = matching_states[state.lower()]

    # Check whether this crop and state combination exists
    selected_records = data[
        (data["state"] == state) &
        (data["crop"] == crop)
    ]

    if selected_records.empty:

        print(
            "\nNo historical records found for this "
            "crop and state combination."
        )
        return

    # Prepare input
    new_data = pd.DataFrame({
        "state": [state],
        "crop": [crop]
    })

    # Apply the same one-hot encoding columns as training
    new_encoded = pd.get_dummies(
        new_data,
        dtype=float
    )

    new_encoded = new_encoded.reindex(
        columns=feature_columns,
        fill_value=0
    )

    new_encoded["year"] = float(year)

    new_X = new_encoded.to_numpy(dtype=float)

    # Add intercept
    new_X = np.column_stack([
        np.ones(len(new_X)), new_X
    ])

    # Use selected model
    if best_model == "Linear Regression":

        prediction = new_X @ linear_coefficients

    else:

        new_X_poly = np.column_stack([
            new_X,
            new_X[:, year_position] ** 2
        ])

        prediction = new_X_poly @ poly_coefficients

    predicted_yield = max(0, float(prediction[0]))

    print("\n======================================")
    print("       CROP YIELD PREDICTION")
    print("======================================")
    print("State/UT:", state)
    print("Crop:", crop.title())
    print("Year:", year)
    print("Model Used:", best_model)
    print("--------------------------------------")
    print(
        "Predicted Yield:",
        round(predicted_yield, 2),
        "kg/ha"
    )
    print(
        "Predicted Yield:",
        round(predicted_yield / 1000, 2),
        "tonnes/ha"
    )
    print("======================================")

    print(
        "\nNote: This is a model estimate, "
        "not an actual measured yield."
    )

    return predicted_yield


