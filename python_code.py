# ==========================================
# 6. OUTLIER DETECTION USING IQR
# ==========================================

print("\nOUTLIER DETECTION")

for crop in required_crops:

    values = data.loc[
        data["crop"] == crop, "crop_yield"
    ]

    Q1 = values.quantile(0.25)
    Q3 = values.quantile(0.75)
    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    outliers = values[
        (values < lower) | (values > upper)
    ]

    print(crop.title(), "outliers:", len(outliers))

# ==========================================
# 7. TRAINING AND TESTING DATA
# ==========================================

# Train on years before 2024 and test on 2024
train = data[data["year"] < 2024].copy()
test = data[data["year"] == 2024].copy()

if len(train) == 0 or len(test) == 0:
    raise ValueError(
        "Training or testing data is empty. Check the dataset years."
    )

print("\nTRAINING AND TESTING")
print("Training rows:", len(train))
print("Testing rows:", len(test))
print("Training years:", sorted(train["year"].unique()))
print("Testing years:", sorted(test["year"].unique()))

# One-hot encode state and crop
X_all = pd.get_dummies(
    data[["state", "crop"]],
    dtype=float
)

feature_columns = X_all.columns.tolist()

# Add year as a numerical feature
X_all["year"] = data["year"].astype(float)

y_all = data["crop_yield"].to_numpy(dtype=float)

train_mask = data["year"].to_numpy() < 2024
test_mask = data["year"].to_numpy() == 2024

X_train = X_all.loc[train_mask].to_numpy(dtype=float)
X_test = X_all.loc[test_mask].to_numpy(dtype=float)

y_train = y_all[train_mask]
y_test = y_all[test_mask]

# Add intercept column
X_train = np.column_stack([
    np.ones(len(X_train)), X_train
])

X_test = np.column_stack([
    np.ones(len(X_test)), X_test
])

# ==========================================
# 8. LINEAR REGRESSION
# ==========================================

linear_coefficients = np.linalg.lstsq(
    X_train, y_train, rcond=None
)[0]

linear_predictions = X_test @ linear_coefficients

print("\nLINEAR REGRESSION COMPLETED")

# ==========================================
# 9. POLYNOMIAL REGRESSION
# ==========================================

# Add year squared as an additional feature
year_position = X_all.columns.get_loc("year") + 1

X_train_poly = np.column_stack([
    X_train,
    X_train[:, year_position] ** 2
])

X_test_poly = np.column_stack([
    X_test,
    X_test[:, year_position] ** 2
])

poly_coefficients = np.linalg.lstsq(
    X_train_poly, y_train, rcond=None
)[0]

poly_predictions = X_test_poly @ poly_coefficients

print("POLYNOMIAL REGRESSION COMPLETED")

# ==========================================
# 10. MODEL EVALUATION
# ==========================================

def evaluate_model(actual, predicted):

    mae = np.mean(np.abs(actual - predicted))
    mse = np.mean((actual - predicted) ** 2)
    rmse = np.sqrt(mse)

    ss_total = np.sum(
        (actual - np.mean(actual)) ** 2
    )

    ss_residual = np.sum(
        (actual - predicted) ** 2
    )

    if ss_total == 0:
        r2 = 0
    else:
        r2 = 1 - (ss_residual / ss_total)

    return mae, mse, rmse, r2


linear_metrics = evaluate_model(
    y_test, linear_predictions
)

poly_metrics = evaluate_model(
    y_test, poly_predictions
)

print("\nLINEAR REGRESSION")
print("MAE:", round(linear_metrics[0], 2))
print("MSE:", round(linear_metrics[1], 2))
print("RMSE:", round(linear_metrics[2], 2))
print("R2 Score:", round(linear_metrics[3], 4))

print("\nPOLYNOMIAL REGRESSION")
print("MAE:", round(poly_metrics[0], 2))
print("MSE:", round(poly_metrics[1], 2))
print("RMSE:", round(poly_metrics[2], 2))
print("R2 Score:", round(poly_metrics[3], 4))

# Select model with lower RMSE
